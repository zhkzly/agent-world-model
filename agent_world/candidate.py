def _field_value(field: Any) -> object:
    if field.category == "boolean":
        return False
    if field.category == "integer":
        return 0
    if field.category == "number":
        return 0.0
    if field.category == "list":
        return []
    if field.category == "enum":
        return field.values[0]
    if field.category == "identifier":
        return "public-id"
    if field.category == "timestamp":
        return "1970-01-01T00:00:00Z"
    return ""


# ---------------------------------------------------------------------------
# Framework-provided, design-driven candidate runtime.
# The runtime is generated by the framework (compile_candidate writes it) with
# each tool's declared result_fields + transitions embedded as `_DESIGN`.  It
# applies the declared transitions on invoke and returns the declared result
# fields, so its state is correct by construction — the codegen agent does not
# implement the runtime, only the materializer.
# ---------------------------------------------------------------------------
_DESIGN_RUNTIME_BODY = '''import json
import sys
import traceback

OPERATIONS = ("handshake", "reset", "invoke", "snapshot", "close")
_state = {}
_responses = {}


def _default(category, values=()):
    if category == "boolean":
        return False
    if category == "integer":
        return 0
    if category == "number":
        return 0.0
    if category == "list":
        return []
    if category == "enum":
        return values[0] if values else ""
    if category == "timestamp":
        return "1970-01-01T00:00:00Z"
    return ""


def _init():
    global _state
    _state = {
        name: {
            field["name"]: _default(field.get("category", "text"), field.get("values", ()))
            for field in spec.get("result_fields", ())
        }
        for name, spec in _DESIGN.items()
    }


_MISSING = object()


def _resolve(name, arguments, current):
    if name in arguments:
        return arguments[name]
    if name in current:
        return current[name]
    return _MISSING


def _holds(rule, arguments, current):
    for pred in rule.get("when", ()):
        field = pred.get("field")
        op = pred.get("operator")
        left = _resolve(field, arguments, current)
        if op == "exists":
            ok = left is not _MISSING
        elif op == "not_exists":
            ok = left is _MISSING
        else:
            right = pred.get("value")
            if left is _MISSING:
                ok = False
            elif op == "eq":
                ok = type(left) is type(right) and left == right
            elif op == "ne":
                ok = type(left) is type(right) and left != right
            elif op in ("lt", "le", "gt", "ge"):
                ok = (
                    type(left) is type(right)
                    and type(left) in (int, float, str)
                    and {
                        "lt": left < right,
                        "le": left <= right,
                        "gt": left > right,
                        "ge": left >= right,
                    }[op]
                )
            elif op == "contains":
                ok = (
                    isinstance(left, (str, list))
                    and (not isinstance(left, str) or isinstance(right, str))
                    and right in left
                )
            elif op == "not_contains":
                ok = (
                    isinstance(left, (str, list))
                    and (not isinstance(left, str) or isinstance(right, str))
                    and right not in left
                )
            else:
                ok = False
        if not ok:
            return False
    return True


def do_invoke(request):
    key = request.get("idempotency_key")
    if key and key in _responses:
        return dict(_responses[key])
    tool = request.get("tool_id")
    spec = _DESIGN.get(tool, {})
    current = _state.get(tool, {})
    arguments = request.get("arguments") or {}
    for rule in spec.get("transitions", ()):
        if not _holds(rule, arguments, current):
            continue
        for effect in rule.get("effects", ()):
            field = effect.get("field")
            operation = effect.get("operation")
            value = effect.get("value")
            if field not in current:
                continue
            if operation == "set":
                current[field] = value
            elif operation == "increment" and isinstance(current[field], (int, float)):
                current[field] = current[field] + value
            elif operation == "decrement" and isinstance(current[field], (int, float)):
                current[field] = current[field] - value
            elif operation == "add" and isinstance(current[field], list):
                current[field] = current[field] + [value]
            elif operation == "remove" and (
                isinstance(current[field], list) and value in current[field]
            ):
                current[field] = [item for item in current[field] if item != value]
    response = {"status": "ok", "result": dict(current)}
    if key:
        _responses[key] = response
    return response


def main():
    for line in sys.stdin:
        closing = False
        try:
            request = json.loads(line)
            operation = request.get("op")
            if operation == "handshake":
                response = {"operations": list(OPERATIONS)}
            elif operation == "reset":
                _init()
                _responses.clear()
                initial_config = request.get("initial_config") or {}
                for tool_name, fields in (initial_config.get("tools") or {}).items():
                    target = _state.get(tool_name)
                    if isinstance(target, dict) and isinstance(fields, dict):
                        for field_name, value in fields.items():
                            if field_name in target:
                                target[field_name] = value
                response = {"status": "ok"}
            elif operation == "invoke":
                response = do_invoke(request)
            elif operation == "snapshot":
                response = {"state": {"tools": _state}}
            elif operation == "close":
                closing = True
                response = {"status": "ok"}
            else:
                response = {"status": "error", "error": "unknown op: " + str(operation)}
        except Exception as exc:  # noqa: BLE001 - never crash the protocol
            response = {
                "status": "error",
                "error": type(exc).__name__ + ": " + str(exc),
                "traceback": traceback.format_exc()[-2000:],
            }
        sys.stdout.write(json.dumps(response) + "\\n")
        sys.stdout.flush()
        if closing:
            break


if __name__ == "__main__":
    main()
'''


def _design_runtime_data(design: DesignContract) -> dict[str, Any]:
    """Project each tool's result_fields + name-based conditional transitions.

    Predicate/effect names MUST resolve through the tool's frozen bindings (the
    same map the design artifact uses); a name bound at multiple semantic
    indexes collapses to the binding name, mirroring _name_to_index.
    """
    data: dict[str, Any] = {}
    for tool in design.tools:
        binding_name = {binding.index: binding.name for binding in tool.bindings}
        transitions: list[dict[str, Any]] = []
        for rule in tool.transitions:
            transitions.append(
                {
                    "when": [
                        dict(
                            field=binding_name.get(pred.left_semantic_index, ""),
                            operator=pred.operator,
                            **(
                                {"value": pred.right}
                                if pred.operator not in {"exists", "not_exists"}
                                else {}
                            ),
                        )
                        for pred in rule.when
                    ],
                    "effects": [
                        {
                            "field": binding_name.get(effect.target_semantic_index, ""),
                            "operation": effect.operation,
                            "value": effect.value,
                        }
                        for effect in rule.effects
                    ],
                }
            )
        data[tool.surface.name] = {
            "result_fields": [
                {"name": field.name, "category": field.category, "values": list(field.values)}
                for field in tool.surface.result_fields
            ],
            "transitions": transitions,
        }
    return data


def _render_design_driven_runtime(design: DesignContract) -> str:
    return "_DESIGN = " + repr(_design_runtime_data(design)) + "\n\n" + _DESIGN_RUNTIME_BODY


def _source_files_closure(root: Path) -> list[dict[str, Any]]:
    """Content-addressed candidate source closure for resume materialization."""

    files: list[dict[str, Any]] = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        body = path.read_bytes()
        files.append(
            {
                "path": path.relative_to(root).as_posix(),
                "digest": f"sha256:{sha256(body).hexdigest()}",
                "size": len(body),
                "mode": f"{stat.S_IMODE(path.stat().st_mode):04o}",
                "content_b64": base64.b64encode(body).decode("ascii"),
            }
        )
    return files


